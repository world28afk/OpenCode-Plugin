#!/usr/bin/env node
// 把人类可读资产（prompts/*.md、skills/redteam/*.md）生成为内联 TS 模块，
// 避免打包/路径变化后运行时读文件失败（迁移指南 §3 第 2 步）。
//
//   node scripts/sync-assets.mjs
//
// 生成:
//   .opencode/plugins/oc-purge/src/prompts.ts   (默认提示词 + 能力协议 + 哈希)
//   .opencode/plugins/oc-purge/src/skills.ts    (内置红队技能目录)

import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import { gunzipSync } from "node:zlib"
import { basename, dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = join(dirname(fileURLToPath(import.meta.url)), "..")
const plugin = join(root, ".opencode", "plugins", "oc-purge")
const promptsDir = join(plugin, "prompts")
const skillsDir = join(root, "skills", "redteam")
const skillsBundle = join(root, "skills", "redteam.bundle.json.gz")
const srcDir = join(plugin, "src")

const read = (path) => readFileSync(path, "utf8").replace(/\r\n/g, "\n")
const sha256 = (text) => createHash("sha256").update(text, "utf8").digest("hex")

// ── 默认提示词 ────────────────────────────────────────────────────────────
const defaultPrompt = read(join(promptsDir, "default-prompt-inject.md")).trim()

// ── 能力选用协议 ──────────────────────────────────────────────────────────
const capabilityRaw = read(join(promptsDir, "capability-protocol.md"))
const sections = { official: "", redteamLead: "", redteamChild: "" }
{
  const labels = { "redteam-lead": "redteamLead", "redteam-child": "redteamChild" }
  const parts = capabilityRaw.split(/\n?<!--\s*oc-purge:\s*section=([a-z-]+)\s*-->\n?/)
  // parts = [preamble, label, body, label, body, ...]
  for (let i = 1; i < parts.length; i += 2) {
    const key = labels[parts[i]] || "official"
    sections[key] = (parts[i + 1] || "").trim()
  }
}
for (const [key, value] of Object.entries(sections)) {
  if (!value) throw new Error(`capability-protocol.md 缺少 section: ${key}`)
}

// ── 内置提示词方案（scheme-<id>.md） ──────────────────────────────────────
// 首次装载时由 mount.ts 播种到方案库；删掉后不再自动重建（见 seededSchemes）。
const SCHEME_META = {
  "writing-craft": {
    name: "写作模式 · 虚构创作",
    description: "叙事 craft 规则：声音、NPC 认知、场景纪律、感官与露骨度；启用后替换默认提示词。",
  },
}

const builtinSchemes = readdirSync(promptsDir)
  .filter((name) => /^scheme-.+\.md$/.test(name))
  .sort()
  .map((name) => {
    const id = name.replace(/^scheme-/, "").replace(/\.md$/, "")
    const content = read(join(promptsDir, name)).trim()
    const meta = SCHEME_META[id] ?? {}
    return {
      id,
      name: meta.name ?? id,
      description: meta.description ?? "",
      sha256: sha256(content),
      content,
    }
  })

const promptsOut = `// AUTO-GENERATED by scripts/sync-assets.mjs — 请勿手改。
// 上游资产逐字保留: prompts/default-prompt-inject.md (dsh-purge 加密默认提示词, 解封后原文)
//                   prompts/capability-protocol.md

export const DEFAULT_PROMPT_SHA256 = ${JSON.stringify(sha256(defaultPrompt))}
export const DEFAULT_PROMPT = ${JSON.stringify(defaultPrompt)}

export interface CapabilityProtocol {
  readonly official: string
  readonly redteamLead: string
  readonly redteamChild: string
}

export const CAPABILITY_PROTOCOL: CapabilityProtocol = {
  official: ${JSON.stringify(sections.official)},
  redteamLead: ${JSON.stringify(sections.redteamLead)},
  redteamChild: ${JSON.stringify(sections.redteamChild)},
}

export type CapabilityRole = "official" | "redteamLead" | "redteamChild"

export interface BuiltinScheme {
  readonly id: string
  readonly name: string
  readonly description: string
  readonly sha256: string
  readonly content: string
}

export const BUILTIN_SCHEMES: readonly BuiltinScheme[] = ${JSON.stringify(builtinSchemes, null, 2)} as const
`

writeFileSync(join(srcDir, "prompts.ts"), promptsOut, "utf8")

// ── 内置红队技能 ──────────────────────────────────────────────────────────
// 权威来源是 skills/redteam.bundle.json.gz（压缩资产, 防终端安全软件误删明文）。
// 同步时按需把文件还原到 skills/redteam/（human-readable 副本）。
// 条目键有两种形态：
//   扁平技能  active-scan.md                → skills/redteam/active-scan.md
//   目录技能  game-hacking/references/x.md  → skills/redteam/game-hacking/references/x.md
if (!existsSync(skillsBundle)) {
  throw new Error(`缺少技能资产包: ${skillsBundle}（可先用 scripts/verify.mjs 检查）`)
}
const bundle = JSON.parse(gunzipSync(readFileSync(skillsBundle)).toString("utf8"))
const bundleFiles = bundle.files && typeof bundle.files === "object" ? bundle.files : {}
const bundleKeys = Object.keys(bundleFiles).sort()
if (!bundleKeys.length) throw new Error("redteam.bundle.json.gz 中没有技能文件")

/** 条目键 → { id, path }；path 是技能目录内的相对路径。 */
function parseKey(key) {
  const slash = key.indexOf("/")
  if (slash < 0) return { id: key.replace(/\.md$/, ""), path: "SKILL.md" }
  return { id: key.slice(0, slash), path: key.slice(slash + 1) }
}

if (!existsSync(skillsDir)) mkdirSync(skillsDir, { recursive: true })
for (const key of bundleKeys) {
  const { id, path } = parseKey(key)
  const target = key.includes("/") ? join(skillsDir, id, ...path.split("/")) : join(skillsDir, basename(key))
  const text = String(bundleFiles[key]).replace(/\r\n/g, "\n")
  // 只在缺失或内容不一致时写回, 避免无谓改写触发安全软件扫描
  if (!existsSync(target) || readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== text) {
    mkdirSync(dirname(target), { recursive: true })
    writeFileSync(target, text, "utf8")
  }
}

/** 从 YAML frontmatter 取 description（支持 `description: |` 块与行内值）。 */
function describe(content, id) {
  const fm = content.match(/^---\n([\s\S]*?)\n---/)
  if (fm) {
    const body = fm[1]
    const block = body.match(/^description:\s*\|\s*\n((?:[ \t]+.*\n?)+)/m)
    if (block) return block[1].replace(/^[ \t]+/gm, "").replace(/\s+/g, " ").trim()
    const inline = body.match(/^description:\s*(.+)$/m)
    if (inline && inline[1].trim() && inline[1].trim() !== "|") return inline[1].trim()
  }
  const title = content.match(/^#\s+(.+)$/m)
  return title ? title[1].trim() : `${id} (dsh-purge bundled red-team skill)`
}

const grouped = new Map()
for (const key of bundleKeys) {
  const { id, path } = parseKey(key)
  if (!grouped.has(id)) grouped.set(id, [])
  grouped.get(id).push({ key, path })
}

const skills = [...grouped.entries()]
  .sort((a, b) => a[0].localeCompare(b[0]))
  .map(([id, entries]) => {
    const primary = entries.find((e) => e.path === "SKILL.md") ?? entries[0]
    const files = entries
      .sort((a, b) => (a.path === "SKILL.md" ? -1 : b.path === "SKILL.md" ? 1 : a.path.localeCompare(b.path)))
      .map((e) => {
        const content = String(bundleFiles[e.key]).replace(/\r\n/g, "\n")
        return { path: e.path, sha256: sha256(content.trim()), content }
      })
    const primaryFile = files.find((f) => f.path === primary.path) ?? files[0]
    return {
      id,
      file: primary.key,
      description: describe(String(bundleFiles[primary.key]).replace(/\r\n/g, "\n"), id),
      sha256: primaryFile.sha256,
      content: primaryFile.content,
      files,
    }
  })

const skillsOut = `// AUTO-GENERATED by scripts/sync-assets.mjs — 请勿手改。
// 上游资产逐字保留: skills/redteam/**（dsh-purge 捆绑红队技能 ${skills.length} 项，含目录型技能的 references/）
// 权威来源: skills/redteam.bundle.json.gz（压缩资产, 防终端安全软件误删明文）

export interface BundledSkillFile {
  /** 技能目录内的相对路径，主文档固定为 SKILL.md。 */
  readonly path: string
  readonly sha256: string
  readonly content: string
}

export interface BundledSkill {
  readonly id: string
  /** 主文档在资产包里的键（扁平技能是 <id>.md，目录技能是 <id>/SKILL.md）。 */
  readonly file: string
  readonly description: string
  readonly sha256: string
  readonly content: string
  readonly files: readonly BundledSkillFile[]
}

export const BUNDLED_SKILLS: readonly BundledSkill[] = ${JSON.stringify(skills, null, 2)} as const
`

writeFileSync(join(srcDir, "skills.ts"), skillsOut, "utf8")

process.stdout.write(
  `sync-assets: prompt=${defaultPrompt.length}B sha=${sha256(defaultPrompt).slice(0, 12)} skills=${skills.length}` +
    ` files=${bundleKeys.length} schemes=${builtinSchemes.length}\n`,
)
